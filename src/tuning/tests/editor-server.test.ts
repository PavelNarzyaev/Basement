import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from 'vite';
import { TuningDevelopmentServer } from '../editor/TuningDevelopmentServer.ts';
import { TuningAgentClient } from '../editor/TuningAgentClient.ts';
import { TuningSettingsPatchDto } from '../contracts/TuningSettingsPatchDto.ts';

test('editor preview, validation, save and reset share one state and only save writes defaults', async (context) => {
  const root = await mkdtemp(join(tmpdir(), 'basement-tuning-'));
  const folder = join(root, 'src/tuning/contracts');
  await mkdir(folder, { recursive: true });
  const file = join(folder, 'tuningDefaults.json');
  const defaults = { unladenMovementSpeed: 4, carryingMovementSpeed: 2.5, lampColor: '#ffdfaa' };
  await writeFile(file, JSON.stringify(defaults));
  const server = await createServer({ configFile: false, root, server: { host: '127.0.0.1', port: 0 }, plugins: [new TuningDevelopmentServer().createPlugin()] });
  context.after(async () => { await server.close(); await rm(root, { recursive: true, force: true }); });
  await server.listen();
  const address = server.httpServer!.address();
  assert.ok(address && typeof address !== 'string');
  const baseUrl = `http://127.0.0.1:${address.port}`;
  const client = new TuningAgentClient(baseUrl);
  const preview = await client.updateSettings(new TuningSettingsPatchDto(6, undefined, '#123ABC'));
  assert.equal(preview.current.unladenMovementSpeed, 6);
  assert.equal(preview.current.carryingMovementSpeed, 2.5);
  assert.equal(preview.current.lampColor, '#123abc');
  assert.equal(preview.hasUnsavedChanges, true);
  assert.deepEqual(JSON.parse(await readFile(file, 'utf8')), defaults);
  await assert.rejects(client.updateSettings(new TuningSettingsPatchDto(-1)), /between/);
  const rejected = await fetch(`${baseUrl}/__editor/settings`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ unknownField: 2 }) });
  assert.equal(rejected.status, 400);
  const foreign = await fetch(`${baseUrl}/__editor/settings/save`, { method: 'POST', headers: { Origin: 'https://example.com' } });
  assert.equal(foreign.status, 400);
  const saved = await client.saveSettings();
  assert.equal(saved.hasUnsavedChanges, false);
  assert.deepEqual(JSON.parse(await readFile(file, 'utf8')), saved.current);
  await client.updateSettings(new TuningSettingsPatchDto(2));
  const reset = await client.resetSettings();
  assert.equal(reset.current.unladenMovementSpeed, 6);
  assert.equal(reset.hasUnsavedChanges, false);
});
